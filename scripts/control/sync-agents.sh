#!/usr/bin/env bash
# ==============================================================================
# brainsOS: Multi-Agent Fleet Manifest Synchronization & Orchestration Engine
# Renders docker-compose.agents.yml and config/caddy/agents.caddy from config/agents.yaml.
# Scaffolds host storage partitions, permissions, and LiteLLM virtual keys.
# ==============================================================================

set -euo pipefail

# Visual styling
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BOLD='\033[1m'
NC='\033[0m'

log_info() { echo -e "${BLUE}[INFO]${NC} $*"; }
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $*"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*" >&2; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(git -C "${SCRIPT_DIR}" rev-parse --show-toplevel 2>/dev/null || true)"
if [ -z "${REPO_ROOT}" ]; then
  _check_dir="${SCRIPT_DIR}"
  while [ "${_check_dir}" != "/" ] && [ -n "${_check_dir}" ]; do
    if [ -f "${_check_dir}/config/agents.yaml" ] || [ -d "${_check_dir}/.git" ]; then
      REPO_ROOT="${_check_dir}"
      break
    fi
    _check_dir="$(dirname "${_check_dir}")"
  done
  [ -z "${REPO_ROOT}" ] && REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
fi

cd "${REPO_ROOT}"

CALLER_BRAINSOS_DOMAIN="${BRAINSOS_DOMAIN:-}"
CALLER_ACME_DNS_PROVIDER="${ACME_DNS_PROVIDER:-}"

# Load environment variables
if [ -f .env ]; then
  set -a
  . ./.env
  set +a
elif [ -f .env.example ]; then
  set -a
  . ./.env.example
  set +a
fi

[ -n "${CALLER_BRAINSOS_DOMAIN}" ] && BRAINSOS_DOMAIN="${CALLER_BRAINSOS_DOMAIN}"
[ -n "${CALLER_ACME_DNS_PROVIDER}" ] && ACME_DNS_PROVIDER="${CALLER_ACME_DNS_PROVIDER}"
export BRAINSOS_DOMAIN="${BRAINSOS_DOMAIN:-brainsos.local}"
export ACME_DNS_PROVIDER="${ACME_DNS_PROVIDER:-}"

if [ -n "${GITHUB_TOKEN_CINDY:-}" ] && [ -z "${GITHUB_BASIC_AUTH_CINDY:-}" ]; then
  GITHUB_BASIC_AUTH_CINDY="$(printf 'x-access-token:%s' "${GITHUB_TOKEN_CINDY}" | base64 | tr -d '\r\n')"
  export GITHUB_BASIC_AUTH_CINDY
  if [ -f .env ] && grep -q "^GITHUB_BASIC_AUTH_CINDY=" .env; then
    sed -i.bak "s|^GITHUB_BASIC_AUTH_CINDY=.*|GITHUB_BASIC_AUTH_CINDY=${GITHUB_BASIC_AUTH_CINDY}|" .env && rm -f .env.bak
  elif [ -f .env ]; then
    echo "GITHUB_BASIC_AUTH_CINDY=${GITHUB_BASIC_AUTH_CINDY}" >> .env
  fi
fi

if [ -z "${MANIFEST_FILE:-}" ]; then
  if [ -f "${REPO_ROOT}/config/agents.local.yaml" ]; then
    MANIFEST_FILE="${REPO_ROOT}/config/agents.local.yaml"
    log_info "Using host-local fleet manifest override: config/agents.local.yaml"
  elif [ -f "${REPO_ROOT}/config/agents.override.yaml" ]; then
    MANIFEST_FILE="${REPO_ROOT}/config/agents.override.yaml"
    log_info "Using host-local fleet manifest override: config/agents.override.yaml"
  else
    MANIFEST_FILE="${REPO_ROOT}/config/agents.yaml"
  fi
fi
export MANIFEST_FILE
OUTPUT_COMPOSE="${REPO_ROOT}/docker-compose.agents.yml"
OUTPUT_CADDY="${REPO_ROOT}/config/caddy/agents.caddy"
OUTPUT_TLS="${REPO_ROOT}/config/caddy/tls_policy.caddy"
OUTPUT_CONTINUE="${REPO_ROOT}/config/editor/continue_config.yaml"
OUTPUT_CONTINUE_JSON="${REPO_ROOT}/config/editor/continue_config.json"

# Ensure python3 with yaml is available
PYTHON_BIN="python3"
if [ -x "${REPO_ROOT}/.venv/bin/python" ]; then
  PYTHON_BIN="${REPO_ROOT}/.venv/bin/python"
fi

if ! ${PYTHON_BIN} -c "import yaml" >/dev/null 2>&1; then
  log_error "Python PyYAML package is required to parse ${MANIFEST_FILE}."
  exit 1
fi

if [ ! -f "${MANIFEST_FILE}" ]; then
  log_error "Fleet manifest not found at ${MANIFEST_FILE}."
  exit 1
fi

MODE="${1:-sync}"

