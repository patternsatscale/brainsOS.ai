provision_virtual_keys() {
  LITELLM_PORT="${LITELLM_PORT:-4000}"
  LITELLM_MASTER_KEY="${LITELLM_MASTER_KEY:-}"
  LITELLM_URL="http://127.0.0.1:${LITELLM_PORT}"

  if ! curl -s -o /dev/null -w "%{http_code}" "${LITELLM_URL}/health/liveness" | grep -qE '^(200|401|405)'; then
    log_info "LiteLLM control plane is not currently running. Virtual keys will be seeded upon control plane boot."
    return 0
  fi

  if [ -z "${LITELLM_MASTER_KEY}" ]; then
    log_warn "LITELLM_MASTER_KEY is unset; skipping LiteLLM virtual key seeding."
    return 0
  fi

  log_info "Provisioning fleet virtual keys in LiteLLM Control Plane (${LITELLM_URL})..."

  MANIFEST_FILE="${MANIFEST_FILE}" ${PYTHON_BIN} - << EOF
import os
import urllib.request
import json
import yaml

repo_root = os.getcwd()
manifest_path = os.environ.get("MANIFEST_FILE", os.path.join(repo_root, "config", "agents.yaml"))
with open(manifest_path, "r", encoding="utf-8") as f:
    manifest = yaml.safe_load(f)

master_key = os.environ.get("LITELLM_MASTER_KEY", "")
litellm_url = "${LITELLM_URL}"

for agent in manifest.get("agents", []):
    agent_id = agent["id"]
    budget = float(agent.get("routing", {}).get("budget_monthly_usd", 25.0))
    key_name = agent.get("routing", {}).get("virtual_key", f"{agent_id.upper().replace('-', '_')}_LITELLM_KEY")
    key_val = os.environ.get(key_name, f"sk-brainsos-{agent_id}-key")

    check_url = f"{litellm_url}/key/info?key={key_val}"
    req = urllib.request.Request(check_url, headers={"Authorization": f"Bearer {master_key}"})
    key_exists = False
    try:
        with urllib.request.urlopen(req) as resp:
            if resp.status == 200:
                key_exists = True
    except Exception:
        pass

    key_payload = {
        "key": key_val,
        "key_alias": f"brainsos-agent-{agent_id}",
        "user_id": agent_id,
        "max_budget": budget,
        "models": [],
        "metadata": {
            "agent_id": agent_id,
            "project": "brainsos"
        }
    }
    if not key_exists:
        gen_url = f"{litellm_url}/key/generate"
        payload = json.dumps(key_payload).encode("utf-8")
        gen_req = urllib.request.Request(
            gen_url,
            data=payload,
            headers={
                "Authorization": f"Bearer {master_key}",
                "Content-Type": "application/json"
            }
        )
        try:
            with urllib.request.urlopen(gen_req) as resp:
                print(f"[SUCCESS] Provisioned virtual key for agent '{agent_id}' (alias: brainsos-agent-{agent_id}, budget: \${budget:.2f}).")
        except Exception as e:
            print(f"[WARN] Failed to provision key for '{agent_id}': {e}")
    else:
        update_url = f"{litellm_url}/key/update"
        payload = json.dumps(key_payload).encode("utf-8")
        update_req = urllib.request.Request(
            update_url,
            data=payload,
            headers={
                "Authorization": f"Bearer {master_key}",
                "Content-Type": "application/json"
            }
        )
        try:
            with urllib.request.urlopen(update_req) as resp:
                print(f"[INFO] Synchronized virtual key identity and metadata for agent '{agent_id}' in LiteLLM DB.")
        except Exception:
            print(f"[INFO] Virtual key for agent '{agent_id}' is already registered in LiteLLM DB.")
EOF
}

