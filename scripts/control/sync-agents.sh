#!/usr/bin/env bash
# ==============================================================================
# Project Titan: Multi-Agent Fleet Manifest Synchronization & Orchestration Engine
# Renders docker-compose.agents.yml and config/caddy/agents.caddy from config/agents.yaml.
# Scaffolds host storage partitions, permissions, and LiteLLM virtual keys.
# ==============================================================================

set -euo pipefail

# Visual styling
GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BOLD='\033[1m'
NC='\033[0m'

log_info() { echo -e "${BLUE}[INFO]${NC} $*"; }
log_success() { echo -e "${GREEN}[SUCCESS]${NC} $*"; }
log_warn() { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*" >&2; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(git -C "${SCRIPT_DIR}" rev-parse --show-toplevel 2>/dev/null || true)"
if [ -z "${REPO_ROOT}" ]; then
  _check_dir="${SCRIPT_DIR}"
  while [ "${_check_dir}" != "/" ] && [ -n "${_check_dir}" ]; do
    if [ -f "${_check_dir}/config/agents.yaml" ] || [ -d "${_check_dir}/.git" ]; then
      REPO_ROOT="${_check_dir}"
      break
    fi
    _check_dir="$(dirname "${_check_dir}")"
  done
  [ -z "${REPO_ROOT}" ] && REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
fi

cd "${REPO_ROOT}"

# Load environment variables
if [ -f .env ]; then
  set -a
  . ./.env
  set +a
elif [ -f .env.example ]; then
  set -a
  . ./.env.example
  set +a
fi

if [ -n "${GITHUB_TOKEN_CINDY:-}" ] && [ -z "${GITHUB_BASIC_AUTH_CINDY:-}" ]; then
  GITHUB_BASIC_AUTH_CINDY="$(printf 'x-access-token:%s' "${GITHUB_TOKEN_CINDY}" | base64 | tr -d '\r\n')"
  export GITHUB_BASIC_AUTH_CINDY
  if [ -f .env ] && grep -q "^GITHUB_BASIC_AUTH_CINDY=" .env; then
    sed -i.bak "s|^GITHUB_BASIC_AUTH_CINDY=.*|GITHUB_BASIC_AUTH_CINDY=${GITHUB_BASIC_AUTH_CINDY}|" .env && rm -f .env.bak
  elif [ -f .env ]; then
    echo "GITHUB_BASIC_AUTH_CINDY=${GITHUB_BASIC_AUTH_CINDY}" >> .env
  fi
fi

if [ -z "${MANIFEST_FILE:-}" ]; then
  if [ -f "${REPO_ROOT}/config/agents.local.yaml" ]; then
    MANIFEST_FILE="${REPO_ROOT}/config/agents.local.yaml"
    log_info "Using host-local fleet manifest override: config/agents.local.yaml"
  elif [ -f "${REPO_ROOT}/config/agents.override.yaml" ]; then
    MANIFEST_FILE="${REPO_ROOT}/config/agents.override.yaml"
    log_info "Using host-local fleet manifest override: config/agents.override.yaml"
  else
    MANIFEST_FILE="${REPO_ROOT}/config/agents.yaml"
  fi
fi
export MANIFEST_FILE
OUTPUT_COMPOSE="${REPO_ROOT}/docker-compose.agents.yml"
OUTPUT_CADDY="${REPO_ROOT}/config/caddy/agents.caddy"

# Ensure python3 with yaml is available
PYTHON_BIN="python3"
if [ -x "${REPO_ROOT}/.venv/bin/python" ]; then
  PYTHON_BIN="${REPO_ROOT}/.venv/bin/python"
fi

if ! ${PYTHON_BIN} -c "import yaml" >/dev/null 2>&1; then
  log_error "Python PyYAML package is required to parse ${MANIFEST_FILE}."
  exit 1
fi

if [ ! -f "${MANIFEST_FILE}" ]; then
  log_error "Fleet manifest not found at ${MANIFEST_FILE}."
  exit 1
fi

MODE="${1:-sync}"

# ------------------------------------------------------------------------------
# Core Generator in Python
# ------------------------------------------------------------------------------
render_manifest() {
  MANIFEST_FILE="${MANIFEST_FILE}" ${PYTHON_BIN} - << 'EOF'
import os
import sys
import yaml

repo_root = os.getcwd()
manifest_path = os.environ.get("MANIFEST_FILE", os.path.join(repo_root, "config", "agents.yaml"))

with open(manifest_path, "r", encoding="utf-8") as f:
    manifest = yaml.safe_load(f)

manifest_rel = os.path.relpath(manifest_path, repo_root)
agents = manifest.get("agents", [])
enabled_agents = [a for a in agents if a.get("enabled", True)]

# 1. Render docker-compose.agents.yml
compose_lines = [
    "# ==============================================================================",
    "# Project Titan: Declarative Multi-Agent Fleet Services",
    f"# Auto-generated by scripts/control/sync-agents.sh from {manifest_rel}.",
    f"# DO NOT EDIT DIRECTLY. Make changes in {manifest_rel} and re-run sync.",
    "# ==============================================================================",
    "",
    "services:",
]

for agent in enabled_agents:
    agent_id = agent["id"]
    name = agent.get("name", f"Agent {agent_id}")
    runtime = agent.get("runtime", "hermes")
    port = agent.get("comms", {}).get("port", 8642)
    dash_port = agent.get("comms", {}).get("dashboard_port", 9119)
    signal_enabled = agent.get("comms", {}).get("signal", {}).get("enabled", False)
    tg_config = agent.get("comms", {}).get("telegram", {})
    telegram_enabled = tg_config.get("enabled", False)
    tg_bot = tg_config.get("bot_name", tg_config.get("bot_profile", f"@{agent_id}_bot"))
    tg_token_env = tg_config.get("token_env", f"TELEGRAM_BOT_TOKEN_{agent_id.upper().replace('-', '_')}")
    tg_users_env = tg_config.get("allowed_users_env", f"TELEGRAM_ALLOWED_USERS_{agent_id.upper().replace('-', '_')}")

    mem_path = agent.get("memory", {}).get("path", f"./data/memories/{agent_id}")
    work_path = agent.get("workspace", {}).get("path", f"./data/workspace/{agent_id}")
    site_path = agent.get("workspace", {}).get("site_path")
    canvas_mount = agent.get("workspace", {}).get("canvas_mount", "/app/html")
    key_name = agent.get("routing", {}).get("virtual_key", f"HERMES_{agent_id.upper().replace('-', '_')}_KEY")

    volume_lines = [
        f"      # L3: Memory Plane (pure OKF markdown)",
        f"      - {mem_path}:/memories",
        f"      # Read-only configuration",
        f"      - ./config/hermes:/app/config:ro",
        f"      # L3: Unprivileged Workspace Sandbox",
        f"      - {work_path}:/opt/data",
        f"      - {work_path}:/workspace",
    ]

    if site_path:
        volume_lines.append(f"      # Dedicated Public HTML Canvas")
        volume_lines.append(f"      - {site_path}:{canvas_mount}")
        protected_paths = agent.get("workspace", {}).get("protected_paths", [])
        for prot_path in protected_paths:
            prot_clean = prot_path.strip("/")
            volume_lines.append(f"      # Masked / Read-Only Protected Path")
            volume_lines.append(f"      - {site_path}/{prot_clean}:{canvas_mount}/{prot_clean}:ro")
        write_safe_root = f"/opt/data:/workspace:{canvas_mount}"
        workspace_dir_env = "/workspace"
    else:
        write_safe_root = "/opt/data"
        workspace_dir_env = "/opt/data"

    git_config = agent.get("git", {})
    git_env_lines = []
    if git_config:
        proxy_host = git_config.get("proxy_host", "github-proxy.titan.local")
        git_user = git_config.get("user_name", f"Agent {agent_id}")
        git_email = git_config.get("user_email", f"{agent_id}@titan.local")
        git_env_lines = [
            f"      - GH_HOST={proxy_host}",
            f"      - GIT_AUTHOR_NAME={git_user}",
            f"      - GIT_AUTHOR_EMAIL={git_email}",
            f"      - GIT_COMMITTER_NAME={git_user}",
            f"      - GIT_COMMITTER_EMAIL={git_email}",
            f"      - GIT_TERMINAL_PROMPT=0",
        ]
        volume_lines.append(f"      # In-Transit Caddy Internal PKI CA Mount")
        volume_lines.append(f"      - caddy_data:/etc/ssl/caddy:ro")

    compose_lines.extend([
        f"  # --------------------------------------------------------------------------",
        f"  # L2: Agent Core Unit: {name} ({agent_id})",
        f"  # --------------------------------------------------------------------------",
        f"  agent-{agent_id}:",
        f"    build:",
        f"      context: .",
        f"      dockerfile: docker/hermes/Dockerfile",
        f"    image: titan-hermes:latest",
        f"    container_name: titan-agent-{agent_id}",
        f"    restart: unless-stopped",
        f"    security_opt:",
        f"      - \"no-new-privileges:true\"",
        f"    ports:",
        f"      - \"127.0.0.1:{port}:{port}\"",
        f"      - \"127.0.0.1:{dash_port}:{dash_port}\"",
        f"    extra_hosts:",
        f"      - \"host.docker.internal:host-gateway\"",
        f"      - \"proxy.local:host-gateway\"",
        f"      - \"litellm:host-gateway\"",
        f"      - \"langfuse.titan.local:${{LANGFUSE_HOST_IP:-host-gateway}}\"",
        f"    volumes:",
    ] + volume_lines + [
        f"    working_dir: /opt/data",
        f"    environment:",
        f"      - PUID=${{PUID:-1000}}",
        f"      - PGID=${{PGID:-1000}}",
        f"      - HERMES_DASHBOARD=1",
        f"      - HERMES_PORT={port}",
        f"      - HERMES_DASHBOARD_PORT={dash_port}",
        f"      - HERMES_DASHBOARD_BASIC_AUTH_USERNAME=${{HERMES_DASHBOARD_USER:-admin}}",
        f"      - HERMES_DASHBOARD_BASIC_AUTH_PASSWORD=${{HERMES_DASHBOARD_PASSWORD:-titan_admin_secret}}",
        f"      - HERMES_LITELLM_KEY=${{{key_name}:-sk-titan-{agent_id}-key}}",
        f"      - CUSTOM_API_KEY=${{{key_name}:-sk-titan-{agent_id}-key}}",
        f"      - OPENAI_API_KEY=${{{key_name}:-sk-titan-{agent_id}-key}}",
        f"      - OPENAI_BASE_URL=http://proxy.local:${{LITELLM_PORT:-4000}}/v1",
        f"      - PROXY_URL=http://proxy.local:${{LITELLM_PORT:-4000}}/v1",
        f"      - LITELLM_URL=http://proxy.local:${{LITELLM_PORT:-4000}}/v1",
        f"      - MEMORY_DIR=/memories",
        f"      - WORKSPACE_DIR={workspace_dir_env}",
        f"      - HERMES_WRITE_SAFE_ROOT={write_safe_root}",
        f"      - INFERENCE_NUM_CTX=${{INFERENCE_NUM_CTX:-4096}}",
        f"      - HERMES_GATEWAY_BOOTSTRAP_STATE=running",
        f"      - API_SERVER_HOST=0.0.0.0",
        f"      - API_SERVER_PORT={port}",
        f"      - API_SERVER_KEY=${{API_SERVER_KEY:-}}",
        f"      - SIGNAL_HTTP_URL=http://signal-cli:8080",
        f"      - SIGNAL_ACCOUNT=${{SIGNAL_ACCOUNT:-}}",
        f"      - SIGNAL_ALLOWED_USERS=${{SIGNAL_ALLOWED_USERS:-}}",
        f"      - TELEGRAM_BOT_NAME={tg_bot}",
        f"      - TELEGRAM_BOT_TOKEN=${{{tg_token_env}:-${{TELEGRAM_BOT_TOKEN:-}}}}",
        f"      - TELEGRAM_ALLOWED_USERS=${{{tg_users_env}:-${{TELEGRAM_ALLOWED_USERS:-}}}}",
        f"      - LANGFUSE_OTEL_AUTH=${{LANGFUSE_OTEL_AUTH:-}}",
    ] + git_env_lines + [
        f"    command: [\"sleep\", \"infinity\"]",
        f"    depends_on:",
        f"      - signal-cli",
        f"    networks:",
        f"      - titan-ingress",
        f"      - titan-internal",
        "",
    ])

has_caddy_volume = any(a.get("git") for a in enabled_agents)
if has_caddy_volume:
    compose_lines.extend([
        "volumes:",
        "  caddy_data:",
        "    name: titan_caddy_data",
        "",
    ])

# 2. Render config/caddy/agents.caddy
caddy_lines = [
    "# ==============================================================================",
    "# Project Titan: Ingress Reverse Proxy Routes for Agent Units (L1: Comms & UX)",
    f"# Auto-generated by scripts/control/sync-agents.sh from {manifest_rel}.",
    f"# DO NOT EDIT DIRECTLY. Make changes in {manifest_rel} and re-run sync.",
    "# ==============================================================================",
    "",
]

for idx, agent in enumerate(enabled_agents):
    agent_id = agent["id"]
    name = agent.get("name", f"Agent {agent_id}")
    port = agent.get("comms", {}).get("port", 8642)
    dash_port = agent.get("comms", {}).get("dashboard_port", 9119)
    subdomain = agent.get("comms", {}).get("subdomain", f"{agent_id}.titan.local")

    # Clean host routing - zero legacy debt
    sub_prefix = subdomain.split(".")[0]
    host_list = [f"http://{subdomain}", f"https://{subdomain}", f"http://{sub_prefix}.localhost", f"https://{sub_prefix}.localhost"]
    api_host_list = [f"http://api.{subdomain}", f"https://api.{subdomain}", f"http://api.{sub_prefix}.localhost", f"https://api.{sub_prefix}.localhost"]

    if agent_id != sub_prefix:
        host_list.extend([f"http://{agent_id}.localhost", f"https://{agent_id}.localhost"])
        api_host_list.extend([f"http://api.{agent_id}.localhost", f"https://api.{agent_id}.localhost"])

    hosts_str = ", ".join(host_list)
    api_hosts_str = ", ".join(api_host_list)

    caddy_lines.extend([
        f"# ------------------------------------------------------------------------------",
        f"# Agent Unit: {name} ({agent_id}) - Dashboard & Console",
        f"# ------------------------------------------------------------------------------",
        f"{hosts_str} {{",
        f"	tls internal",
        f"	encode gzip zstd",
        f"	log {{",
        f"		output stdout",
        f"		format console",
        f"	}}",
        f"	reverse_proxy titan-agent-{agent_id}:{dash_port} {{",
        f"		flush_interval -1",
        f"	}}",
        f"}}",
        f"",
        f"# ------------------------------------------------------------------------------",
        f"# Agent Unit: {name} ({agent_id}) - OpenAI-Compatible API",
        f"# ------------------------------------------------------------------------------",
        f"{api_hosts_str} {{",
        f"	tls internal",
        f"	encode gzip zstd",
        f"	log {{",
        f"		output stdout",
        f"		format console",
        f"	}}",
        f"	reverse_proxy titan-agent-{agent_id}:{port} {{",
        f"		flush_interval -1",
        f"	}}",
        f"}}",
        f"",
    ])

rendered_compose = "\n".join(compose_lines).strip() + "\n"
rendered_caddy = "\n".join(caddy_lines).strip() + "\n"

# Output separator for bash parsing
print("__START_COMPOSE__")
sys.stdout.write(rendered_compose)
print("__END_COMPOSE__")
print("__START_CADDY__")
sys.stdout.write(rendered_caddy)
print("__END_CADDY__")
EOF
}

# ------------------------------------------------------------------------------
# Action: Drift Detection (--check)
# ------------------------------------------------------------------------------
if [ "${MODE}" = "--check" ]; then
  log_info "Verifying fleet manifest drift against rendered files..."
  
  RENDERED_OUTPUT=$(render_manifest)
  EXPECTED_COMPOSE=$(echo "${RENDERED_OUTPUT}" | sed -n '/__START_COMPOSE__/,/__END_COMPOSE__/p' | sed '1d;$d')
  EXPECTED_CADDY=$(echo "${RENDERED_OUTPUT}" | sed -n '/__START_CADDY__/,/__END_CADDY__/p' | sed '1d;$d')

  DRIFT_DETECTED=0

  if [ ! -f "${OUTPUT_COMPOSE}" ]; then
    log_error "Missing file: ${OUTPUT_COMPOSE}"
    DRIFT_DETECTED=1
  else
    ACTUAL_COMPOSE=$(cat "${OUTPUT_COMPOSE}")
    if [ "${ACTUAL_COMPOSE}" != "${EXPECTED_COMPOSE}" ]; then
      log_error "Drift detected in ${OUTPUT_COMPOSE}!"
      diff -u <(echo "${ACTUAL_COMPOSE}") <(echo "${EXPECTED_COMPOSE}") || true
      DRIFT_DETECTED=1
    fi
  fi

  if [ ! -f "${OUTPUT_CADDY}" ]; then
    log_error "Missing file: ${OUTPUT_CADDY}"
    DRIFT_DETECTED=1
  else
    ACTUAL_CADDY=$(cat "${OUTPUT_CADDY}")
    if [ "${ACTUAL_CADDY}" != "${EXPECTED_CADDY}" ]; then
      log_error "Drift detected in ${OUTPUT_CADDY}!"
      diff -u <(echo "${ACTUAL_CADDY}") <(echo "${EXPECTED_CADDY}") || true
      DRIFT_DETECTED=1
    fi
  fi

  if [ ${DRIFT_DETECTED} -eq 0 ]; then
    log_success "✓ Fleet configuration is 100% in sync with $(basename "${MANIFEST_FILE}")."
    exit 0
  else
    log_error "Fleet drift check failed! Please run './scripts/control/sync-agents.sh' to reconcile."
    exit 1
  fi
fi

# ------------------------------------------------------------------------------
# Helper: Provision Virtual Keys in LiteLLM Control Plane Database
# ------------------------------------------------------------------------------
provision_virtual_keys() {
  LITELLM_PORT="${LITELLM_PORT:-4000}"
  LITELLM_MASTER_KEY="${LITELLM_MASTER_KEY:-}"
  LITELLM_URL="http://127.0.0.1:${LITELLM_PORT}"

  if ! curl -s -o /dev/null -w "%{http_code}" "${LITELLM_URL}/health/liveness" | grep -qE '^(200|401|405)'; then
    log_info "LiteLLM control plane is not currently running. Virtual keys will be seeded upon control plane boot."
    return 0
  fi

  if [ -z "${LITELLM_MASTER_KEY}" ]; then
    log_warn "LITELLM_MASTER_KEY is unset; skipping LiteLLM virtual key seeding."
    return 0
  fi

  log_info "Provisioning fleet virtual keys in LiteLLM Control Plane (${LITELLM_URL})..."

  MANIFEST_FILE="${MANIFEST_FILE}" ${PYTHON_BIN} - << EOF
import os
import urllib.request
import json
import yaml

repo_root = os.getcwd()
manifest_path = os.environ.get("MANIFEST_FILE", os.path.join(repo_root, "config", "agents.yaml"))
with open(manifest_path, "r", encoding="utf-8") as f:
    manifest = yaml.safe_load(f)

master_key = os.environ.get("LITELLM_MASTER_KEY", "")
litellm_url = "${LITELLM_URL}"

for agent in manifest.get("agents", []):
    agent_id = agent["id"]
    budget = float(agent.get("routing", {}).get("budget_monthly_usd", 25.0))
    key_name = agent.get("routing", {}).get("virtual_key", f"HERMES_{agent_id.upper().replace('-', '_')}_KEY")
    key_val = os.environ.get(key_name, f"sk-titan-{agent_id}-key")

    check_url = f"{litellm_url}/key/info?key={key_val}"
    req = urllib.request.Request(check_url, headers={"Authorization": f"Bearer {master_key}"})
    key_exists = False
    try:
        with urllib.request.urlopen(req) as resp:
            if resp.status == 200:
                key_exists = True
    except Exception:
        pass

    if not key_exists:
        gen_url = f"{litellm_url}/key/generate"
        payload = json.dumps({
            "key": key_val,
            "key_alias": f"titan-agent-{agent_id}",
            "max_budget": budget,
            "models": []
        }).encode("utf-8")
        gen_req = urllib.request.Request(
            gen_url,
            data=payload,
            headers={
                "Authorization": f"Bearer {master_key}",
                "Content-Type": "application/json"
            }
        )
        try:
            with urllib.request.urlopen(gen_req) as resp:
                print(f"[SUCCESS] Provisioned virtual key for agent '{agent_id}' (alias: titan-agent-{agent_id}, budget: \${budget:.2f}).")
        except Exception as e:
            print(f"[WARN] Failed to provision key for '{agent_id}': {e}")
    else:
        print(f"[INFO] Virtual key for agent '{agent_id}' is already registered in LiteLLM DB.")
EOF
}

if [ "${MODE}" = "--provision-keys" ]; then
  provision_virtual_keys
  exit 0
fi

