log_info "Synchronizing Project Titan Multi-Agent Fleet from ${MANIFEST_FILE}..."

RENDERED_OUTPUT=$(render_manifest)
EXPECTED_COMPOSE=$(echo "${RENDERED_OUTPUT}" | sed -n '/__START_COMPOSE__/,/__END_COMPOSE__/p' | sed '1d;$d')
EXPECTED_CADDY=$(echo "${RENDERED_OUTPUT}" | sed -n '/__START_CADDY__/,/__END_CADDY__/p' | sed '1d;$d')

# 1. Write docker-compose.agents.yml
echo "${EXPECTED_COMPOSE}" > "${OUTPUT_COMPOSE}"
log_success "Rendered agent compose topology at ${OUTPUT_COMPOSE}."

# 2. Write config/caddy/agents.caddy
mkdir -p "${REPO_ROOT}/config/caddy"
echo "${EXPECTED_CADDY}" > "${OUTPUT_CADDY}"
log_success "Rendered Caddy ingress configuration at ${OUTPUT_CADDY}."

# 3. Scaffold host storage partitions & permissions for each agent
MANIFEST_FILE="${MANIFEST_FILE}" ${PYTHON_BIN} - << 'EOF'
import os
import shutil
import json
import yaml

repo_root = os.getcwd()
manifest_path = os.environ.get("MANIFEST_FILE", os.path.join(repo_root, "config", "agents.yaml"))
with open(manifest_path, "r", encoding="utf-8") as f:
    manifest = yaml.safe_load(f)

enabled_agents = [a for a in manifest.get("agents", []) if a.get("enabled", True)]

for agent in manifest.get("agents", []):
    agent_id = agent["id"]
    mem_rel = agent.get("memory", {}).get("path", f"./data/memories/agents/{agent_id}")
    work_rel = agent.get("workspace", {}).get("path", f"./data/workspace/{agent_id}")
    site_rel = agent.get("workspace", {}).get("site_path")

    mem_dir = os.path.abspath(os.path.join(repo_root, mem_rel.lstrip("./")))
    work_dir = os.path.abspath(os.path.join(repo_root, work_rel.lstrip("./")))
    os.makedirs(mem_dir, exist_ok=True)
    os.makedirs(work_dir, exist_ok=True)

    if site_rel:
        for prot_path in agent.get("workspace", {}).get("protected_paths", []):
            prot_clean = prot_path.strip("/")
            prot_full = os.path.abspath(os.path.join(repo_root, site_rel.lstrip("./"), prot_clean))
            os.makedirs(prot_full, exist_ok=True)

    # Seamless migration from legacy tenants directory if present and agents dir does not exist
    legacy_mem_dir = os.path.abspath(os.path.join(repo_root, "data", "memories", "tenants", agent_id))
    if os.path.exists(legacy_mem_dir) and not os.path.exists(mem_dir):
        os.makedirs(os.path.dirname(mem_dir), exist_ok=True)
        shutil.move(legacy_mem_dir, mem_dir)

    # Scaffold memory partition (OKF pure markdown structure)
    for sub in ("knowledge", "rules", "logs"):
        sub_dir = os.path.join(mem_dir, sub)
        os.makedirs(sub_dir, exist_ok=True)
        keep = os.path.join(sub_dir, ".gitkeep")
        if not os.path.exists(keep):
            with open(keep, "w") as f:
                f.write("")

    # Seed universal memory purity guardrail rule
    rules_tmpl = os.path.join(repo_root, "config", "memories", "rules", "memory_purity_guardrail.md")
    dest_rule = os.path.join(mem_dir, "rules", "memory_purity_guardrail.md")
    if os.path.exists(rules_tmpl) and not os.path.exists(dest_rule):
        shutil.copyfile(rules_tmpl, dest_rule)

    # Seed persona (SOUL.md) to both memory plane and Hermes runtime workspace
    persona_path = agent.get("persona")
    if persona_path and os.path.exists(os.path.join(repo_root, persona_path)):
        src_persona = os.path.join(repo_root, persona_path)
        shutil.copyfile(src_persona, os.path.join(mem_dir, "SOUL.md"))
        shutil.copyfile(src_persona, os.path.join(work_dir, "SOUL.md"))

    # Seed subagents if configured
    subagents = agent.get("subagents", [])
    subagents_mem_dir = os.path.join(mem_dir, "subagents")
    subagents_work_dir = os.path.join(work_dir, "subagents")
    if subagents:
        os.makedirs(subagents_mem_dir, exist_ok=True)
        os.makedirs(subagents_work_dir, exist_ok=True)
        for sub in subagents:
            sub_id = sub.get("id")
            sub_persona_path = sub.get("persona")
            if sub_id and sub_persona_path and os.path.exists(os.path.join(repo_root, sub_persona_path)):
